/* ─── step 3 — commands + script ────────────────────────── */
function Step3({
  os, certName, onBack,
}: {
  os: OS
  certName: string
  onBack: () => void
}) {
  const cmds = buildCommands(os, certName)
  const displayName = certName.trim() || 'APEN-CA.crt'
  const baseName = displayName.endsWith('.crt') ? displayName : `${displayName}.crt`

  const downloadScript = () => {
    const blob = new Blob([cmds.script], { type: 'text/plain' })
    const url  = URL.createObjectURL(blob)
    const a    = document.createElement('a')
    a.href     = url
    a.download = os === 'el' ? 'trust-apen-ca-el.sh' : 'trust-apen-ca-ubuntu.sh'
    a.click()
    URL.revokeObjectURL(url)
  }

  const osLabel = os === 'el' ? 'Enterprise Linux' : 'Ubuntu'

  return (
    <div className="space-y-6 animate-fade-in">
      <div className="flex items-start gap-3">
        <div className="w-9 h-9 rounded-full bg-cyan-400/15 border border-cyan-400/30
                        flex items-center justify-center flex-shrink-0">
          <CheckCircle2 size={20} className="text-cyan-400" />
        </div>
        <div>
          <h2 className="text-xl font-bold text-white">Commands for {osLabel}</h2>
          <p className="text-slate-400 text-sm mt-1">
            Run these commands on your system to add <code className="code-inline">{baseName}</code> to the trusted CA store.
            Make sure you're in the directory where the certificate file is saved.
          </p>
        </div>
      </div>

      {/* Quick option: download script */}
      <div className="flex flex-col sm:flex-row gap-3 p-4 rounded-xl border border-indigo-400/20"
        style={{ background: 'rgba(99,102,241,0.05)' }}>
        <div className="flex items-start gap-3 flex-1">
          <div className="w-8 h-8 rounded-lg bg-indigo-400/10 flex items-center justify-center flex-shrink-0">
            <FileDown size={16} className="text-indigo-400" />
          </div>
          <div>
            <p className="text-sm font-semibold text-white">One-click automation script</p>
            <p className="text-xs text-slate-400 mt-0.5">
              Download a shell script that runs all three steps automatically.
              Place it in the same folder as your <code className="code-inline text-xs">{baseName}</code> and run it.
            </p>
          </div>
        </div>
        <button onClick={downloadScript}
          className="flex items-center gap-2 px-4 py-2 rounded-lg bg-indigo-400/15 border border-indigo-400/30
                     text-indigo-300 text-xs font-semibold hover:bg-indigo-400/25 transition-colors flex-shrink-0 self-start sm:self-center">
          <Download size={13} />
          Download .sh Script
        </button>
      </div>

      {/* Divider */}
      <div className="flex items-center gap-3">
        <div className="flex-1 h-px bg-white/8" />
        <span className="text-xs text-slate-400 uppercase tracking-widest">or run manually</span>
        <div className="flex-1 h-px bg-white/8" />
      </div>

      {/* Step 1 */}
      <div className="space-y-2">
        <div className="flex items-center gap-2">
          <Terminal size={14} className="text-cyan-400 flex-shrink-0" />
          <p className="text-xs font-bold uppercase tracking-widest text-slate-400">Step 1 — Copy the certificate</p>
        </div>
        <CodeBlock code={cmds.copy} />
        {os === 'ubuntu' && (
          <p className="text-xs text-slate-400 mt-1">
            Ubuntu requires the <code className="code-inline text-xs">.crt</code> extension — make sure the filename ends in <code className="code-inline text-xs">.crt</code>.
          </p>
        )}
      </div>

      {/* Step 2 */}
      <div className="space-y-2">
        <div className="flex items-center gap-2">
          <Terminal size={14} className="text-cyan-400 flex-shrink-0" />
          <p className="text-xs font-bold uppercase tracking-widest text-slate-400">Step 2 — Update the CA trust store</p>
        </div>
        <CodeBlock code={cmds.update} />
        {os === 'ubuntu' && (
          <p className="text-xs text-slate-400 mt-1">
            You'll see a message like <em>"1 added, 0 removed"</em> if the certificate was added successfully.
          </p>
        )}
      </div>

      {/* Step 3 */}
      <div className="space-y-2">
        <div className="flex items-center gap-2">
          <Shield size={14} className="text-cyan-400 flex-shrink-0" />
          <p className="text-xs font-bold uppercase tracking-widest text-slate-400">Step 3 — Verify</p>
        </div>
        <CodeBlock code={cmds.verify} />
        <p className="text-xs text-slate-400 mt-1">
          If the cert is trusted, you'll see the certificate label in the output.
          No output means it wasn't found — re-check the filename and repeat Step 1.
        </p>
      </div>

      {/* Success note */}
      <Callout type="info">
        After trusting the CA certificate, applications like <code className="code-inline">curl</code>,{' '}
        <code className="code-inline">wget</code>, and <code className="code-inline">pip</code> will accept
        APEN internal HTTPS endpoints without certificate errors.
        You may need to restart any running services for changes to take effect.
      </Callout>

      {/* Links to full docs */}
      <div className="flex flex-col sm:flex-row gap-2 pt-2">
        <Link
          href={os === 'el' ? '/docs/el' : '/docs/ub'}
          className="flex items-center gap-2 px-4 py-2 rounded-lg border border-white/10
                     text-slate-400 text-xs hover:text-white hover:border-white/20 transition-colors"
        >
          <ExternalLink size={12} />
          Full {osLabel} documentation
        </Link>
        <Link
          href="/docs"
          className="flex items-center gap-2 px-4 py-2 rounded-lg border border-white/10
                     text-slate-400 text-xs hover:text-white hover:border-white/20 transition-colors"
        >
          <ExternalLink size={12} />
          All OS documentation
        </Link>
      </div>

      <div className="flex justify-between pt-2">
        <button onClick={onBack}
          className="flex items-center gap-2 px-5 py-2.5 rounded-lg border border-white/10
                     text-slate-400 text-sm hover:text-white hover:border-white/25 transition-colors">
          <ChevronLeft size={16} /> Back
        </button>
        <div className="flex items-center gap-2 px-4 py-2.5 rounded-lg bg-emerald-500/10
                        border border-emerald-500/25 text-emerald-400 text-sm font-medium">
          <CheckCircle2 size={16} /> Setup complete
        </div>
      </div>
    </div>
  )
}

/* ─── main wizard ───────────────────────────────────────── */
export function CertsrvWizard() {
  const [step, setStep]         = useState(1)
  const [os, setOs]             = useState<OS>(null)
  const [certName, setCertName] = useState('')

  const handleReset = () => {
    setStep(1)
    setOs(null)
    setCertName('')
  }

  const handleSetOs = (newOs: OS) => {
    if (newOs !== os) {
      setCertName('')
    }
    setOs(newOs)
  }

  return (
    <div className="page-enter">

      <PageHeader
        title="CA Certificate Setup Wizard"
        subtitle="Guides you through downloading and trusting the APEN CA certificate on your Linux system in three steps — no experience required."
        badge="Certificate Services"
        backHref="/certsrv"
        backColor="cyan"
        logo={CERTSRV_PAGE_LOGOS['/certsrv/ca']}
      />

      {/* Wizard body */}
      <div className="max-w-3xl mx-auto px-6 py-10">

        <div className="flex items-center justify-between mb-8">
          <div className="flex-1">
            <StepBar current={step} />
          </div>
          {(os || certName || step > 1) && (
            <button
              onClick={handleReset}
              className="ml-8 flex items-center gap-1.5 px-3 py-1.5 rounded-lg
                         bg-red-400/10 border border-red-400/20 text-red-400
                         text-xs font-semibold hover:bg-red-400/20 transition-colors"
            >
              <RotateCcw size={13} />
              Clear Form
            </button>
          )}
        </div>

        {/* Step card */}
        <div className="rounded-2xl border border-white/8 p-6 sm:p-8"
          style={{ background: 'rgba(10,15,35,0.75)', backdropFilter: 'blur(16px)' }}>

          {step === 1 && (
            <Step1 onNext={() => setStep(2)} />
          )}
          {step === 2 && (
            <Step2
              os={os} setOs={handleSetOs}
              certName={certName} setCertName={setCertName}
              onNext={() => setStep(3)}
              onBack={() => setStep(1)}
            />
          )}
          {step === 3 && (
            <Step3
              os={os}
              certName={certName}
              onBack={() => setStep(2)}
            />
          )}
        </div>

        {/* Help note */}
        <p className="text-center text-xs text-slate-400 mt-6 leading-relaxed">
          Having trouble? Contact the CESC helpdesk via{' '}
          <a href={EXTERNAL_URLS.trackItSelfService}
            target="_blank" rel="noopener noreferrer"
            className="text-cyan-400/70 hover:text-cyan-400 hover:underline transition-colors">
            TrackIt Self-Service
          </a>{' '}
          or refer to the full{' '}
          <Link href="/docs/el" className="text-cyan-400/70 hover:text-cyan-400 hover:underline transition-colors">
            Enterprise Linux
          </Link>{' '}
          /{' '}
          <Link href="/docs/ub" className="text-cyan-400/70 hover:text-cyan-400 hover:underline transition-colors">
            Ubuntu
          </Link>{' '}
          documentation.
        </p>
      </div>
    </div>
  )
}

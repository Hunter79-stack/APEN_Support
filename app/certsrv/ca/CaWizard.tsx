/* ─── types ─────────────────────────────────────────────── */
type OS = 'el' | 'ubuntu' | null

/* ─── step indicator ────────────────────────────────────── */
const STEPS = [
  { id: 1, label: 'Download Cert' },
  { id: 2, label: 'Select OS'     },
  { id: 3, label: 'Apply Trust'   },
]

function StepBubble({ step, current }: { step: typeof STEPS[0]; current: number }) {
  const done    = step.id < current
  const active  = step.id === current
  return (
    <div className="flex flex-col items-center gap-1.5">
      <div className={`w-9 h-9 rounded-full flex items-center justify-center border-2 transition-all duration-300 text-sm font-bold
        ${done   ? 'bg-cyan-400/20 border-cyan-400 text-cyan-400' : ''}
        ${active ? 'bg-cyan-400   border-cyan-400 text-[#060b18]' : ''}
        ${!done && !active ? 'bg-white/5 border-white/15 text-slate-400' : ''}`}>
        {done ? <CheckCircle2 size={18} /> : step.id}
      </div>
      <span className={`text-xs font-medium whitespace-nowrap transition-colors duration-300
        ${active ? 'text-white' : done ? 'text-cyan-400' : 'text-slate-400'}`}>
        {step.label}
      </span>
    </div>
  )
}

function StepBar({ current }: { current: number }) {
  return (
    <div className="flex items-start gap-0 justify-center">
      {STEPS.map((s, i) => (
        <div key={s.id} className="flex items-center">
          <StepBubble step={s} current={current} />
          {i < STEPS.length - 1 && (
            <div className={`w-16 sm:w-24 h-px mt-[-18px] mx-2 transition-colors duration-500
              ${current > s.id ? 'bg-cyan-400/50' : 'bg-white/10'}`} />
          )}
        </div>
      ))}
    </div>
  )
}

/* ─── command builder ───────────────────────────────────── */
function buildCommands(os: OS, certName: string) {
  const name = certName.trim() || 'APEN-CA.crt'
  const base = name.endsWith('.crt') ? name : `${name}.crt`
  const label = base.replace(/\.crt$/i, '')

  if (os === 'el') {
    return {
      copy:   `sudo cp ${base} /etc/pki/ca-trust/source/anchors/`,
      update: `sudo update-ca-trust extract`,
      verify: `trust list | grep -i '${label}'`,
      script: `#!/bin/bash
# APEN CA Certificate Trust Script — Enterprise Linux
# Generated by APEN Support Site
set -e

CERT="${base}"

if [ ! -f "$CERT" ]; then
  echo "ERROR: $CERT not found in current directory."
  echo "Please download the cert from the ${EXTERNAL_URL_LABELS.certificateServices} portal first."
  exit 1
fi

echo "[1/3] Copying $CERT to CA trust anchors..."
sudo cp "$CERT" /etc/pki/ca-trust/source/anchors/

echo "[2/3] Updating CA trust store..."
sudo update-ca-trust extract

echo "[3/3] Verifying..."
trust list | grep -i '${label}' && echo "✓ Certificate trusted successfully." || echo "Certificate label not found — check the cert name."
`,
    }
  }

  // ubuntu
  return {
    copy:   `sudo cp ${base} /usr/local/share/ca-certificates/`,
    update: `sudo update-ca-certificates`,
    verify: `ls /etc/ssl/certs/ | grep -i '${label}'`,
    script: `#!/bin/bash
# APEN CA Certificate Trust Script — Ubuntu
# Generated by APEN Support Site
set -e

CERT="${base}"

if [ ! -f "$CERT" ]; then
  echo "ERROR: $CERT not found in current directory."
  echo "Please download the cert from the ${EXTERNAL_URL_LABELS.certificateServices} portal first."
  exit 1
fi

echo "[1/3] Copying $CERT to CA certificates..."
sudo cp "$CERT" /usr/local/share/ca-certificates/

echo "[2/3] Updating CA certificate store..."
sudo update-ca-certificates

echo "[3/3] Verifying..."
ls /etc/ssl/certs/ | grep -i '${label}' && echo "✓ Certificate trusted successfully." || echo "Certificate label not found — check the cert was copied correctly."
`,
  }
}


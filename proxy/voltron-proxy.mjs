const ENDPOINT_PATH = '/api/voltron-chat'
// 16 MB gives headroom over MAX_ATTACHMENT_BYTES for JSON-string escaping
// (newlines etc.) plus the bounded chat-history text alongside it.
const MAX_BODY_BYTES = 16 * 1024 * 1024
const MAX_MESSAGES = 40
// Applies ONLY to genuine typed chat turns — attachment content is a separate
// field with its own (much larger) limits below, so a big file no longer
// gets silently clipped down to this size.
const MAX_MESSAGE_CHARS = 8000

// ─── File attachments ────────────────────────────────────────────────────────
// Mirrors (and re-validates server-side — never trust the client alone)
// MAX_ASSISTANT_ATTACHMENT_BYTES/CHARS in lib/assistant/policy.ts.
const MAX_ATTACHMENT_BYTES = 10 * 1024 * 1024 // 10 MB
const MAX_ATTACHMENT_CHARS = 10_000_000
// Small enough to paste verbatim into the prompt with no extra round trip.
const ATTACHMENT_INLINE_CHARS = 12_000
// Per-chunk excerpt size for the map step of the summarization pipeline.
const ATTACHMENT_SUMMARY_CHUNK_CHARS = 40_000
// Hard ceiling on how much of a huge file gets processed at all — bounds the
// worst case to ceil(400_000 / 40_000) = 10 map calls + 1 reduce call, so a
// single request can never fan out into an unbounded number of upstream
// calls no matter how large the attached file is.
const ATTACHMENT_MAX_CHARS_TO_SUMMARIZE = 400_000
const ATTACHMENT_SUMMARY_MAX_TOKENS = 400
const ATTACHMENT_REDUCE_MAX_TOKENS = 700

// ─── Site-content grounding ──────────────────────────────────────────────────
// The assistant used to answer ONLY from the hand-maintained system prompt
// below, with a rule telling it to deny anything not spelled out there. That
// made it hallucinate "not documented on the site" for real pages phrased
// differently than the prompt (e.g. "VMware patch list" → the /downloads/vmware
// pages exist and literally mention patch history). We now ground every answer
// in the site's OWN full-text search index (out/search-index.json — the same
// corpus that powers /search, regenerated by scripts/build-search-index.mjs on
// every build). Two layers are injected per request: (1) a compact PAGE MAP of
// every indexed page so the model always knows what exists, and (2) the top few
// pages RETRIEVED for the user's actual question, with their body text, so it
// can answer specifically. No new deps, no network — air-gap friendly.
//
// Path is resolved relative to THIS module (proxy/…) so it works regardless of
// the process working directory; falls back to cwd()/out if that misses.
const __dir = dirname(fileURLToPath(import.meta.url))
const SEARCH_INDEX_CANDIDATES = [
  resolve(__dir, '../out/search-index.json'),
  resolve(process.cwd(), 'out/search-index.json'),
]

let _searchIndex = { pages: [], mtimeMs: -1, path: null }

// Load (and lazily hot-reload on mtime change, so a `next build` is picked up
// without restarting the proxy). Returns [] until a build has produced the
// index — in which case the assistant degrades to the static-prompt behavior.
function getSearchPages() {
  for (const path of SEARCH_INDEX_CANDIDATES) {
    let stat
    try {
      stat = statSync(path)
    } catch {
      continue
    }
    if (path === _searchIndex.path && stat.mtimeMs === _searchIndex.mtimeMs) {
      return _searchIndex.pages
    }
    try {
      const data = JSON.parse(readFileSync(path, 'utf8'))
      const pages = Array.isArray(data) ? data : Array.isArray(data.pages) ? data.pages : []
      _searchIndex = { pages, mtimeMs: stat.mtimeMs, path }
      return pages
    } catch {
      // keep last good copy on a transient read/parse error
      return _searchIndex.pages
    }
  }
  return _searchIndex.pages
}

// Port of the exact scorer used by the site's own /search UI
// (app/search/SearchClient.tsx): title ×8, heading ×4, description ×3, body ×1
// per query term (terms ≥2 chars). Only pages with a positive score are
// returned so we never inject irrelevant context.
function searchSite(pages, query, limit = 6) {
  const terms = String(query || '').toLowerCase().split(/\s+/).filter((t) => t.length >= 2)
  if (terms.length === 0) return []
  const hits = []
  for (const page of pages) {
    const title = String(page.title || '').toLowerCase()
    const desc = String(page.description || '').toLowerCase()
    const headings = (Array.isArray(page.headings) ? page.headings.join(' ') : '').toLowerCase()
    const body = String(page.text || '').toLowerCase()
    let score = 0
    for (const term of terms) {
      let s = 0
      if (title.includes(term)) s += 8
      if (headings.includes(term)) s += 4
      if (desc.includes(term)) s += 3
      if (body.includes(term)) s += 1
      score += s
    }
    if (score > 0) hits.push({ page, score })
  }
  return hits.sort((a, b) => b.score - a.score).slice(0, limit).map((h) => h.page)
}

// One-line-per-page map of the whole site: what exists + where. Keeps the model
// URL-accurate and lets it find pages the curated prompt never mentioned.
function buildPageMap(pages) {
  return pages
    .map((p) => `- [${p.title}](${p.route})${p.description ? ` — ${p.description}` : ''}`)
    .join('\n')
}

// Full body text of the pages most relevant to the current question, plus the
// destinations of any link cards on them. The index strips HTML tags, so a card
// like the home page's "APEN Voltron" tile used to arrive as label text with no
// URL attached — the model knew the service existed but had nowhere to send the
// user, and filled the gap with a made-up path. scripts/build-search-index.mjs
// now records those hrefs (off-site portals and /api/external/* redirector
// paths only; indexed routes are already in the page map).
function buildRetrievedContext(pages) {
  return pages
    .map((p) => {
      const links = Array.isArray(p.links) && p.links.length
        ? `\nLINK DESTINATIONS ON THIS PAGE (real, verbatim URLs — safe to give the user):\n${
          p.links.map((l) => `- ${l.label || l.href} → ${l.href}`).join('\n')}`
        : ''
      return `## ${p.title} (${p.route})\n${String(p.text || '').slice(0, 1600)}${links}`
    })
    .join('\n\n')
}

/* The prompt itself lives in assistant-knowledge.mjs, split into an
   admin-editable knowledge half and code-owned behavior rules. Overrides are
   written by the admin console (site-stats.mjs) and picked up here on the next
   request via an mtime check — same hot-reload trick as the search index, so
   tuning the assistant's answers costs an edit, not a deploy and a restart. */
let _knowledge = { text: null, mtimeMs: -1 }

function effectiveKnowledgeOverride() {
  let stat
  try {
    stat = statSync(ASSISTANT_KNOWLEDGE_FILE)
  } catch {
    _knowledge = { text: null, mtimeMs: -1 }   // override removed → back to default
    return null
  }
  if (stat.mtimeMs === _knowledge.mtimeMs) return _knowledge.text
  try {
    const data = JSON.parse(readFileSync(ASSISTANT_KNOWLEDGE_FILE, 'utf8'))
    const text = typeof data?.knowledge === 'string' ? data.knowledge : null
    _knowledge = { text, mtimeMs: stat.mtimeMs }
  } catch (error) {
    // Keep serving the last good copy rather than silently reverting to the
    // default mid-conversation on a transient read/parse failure.
    console.warn('[voltron] assistant knowledge override unreadable, keeping previous:', error.message)
  }
  return _knowledge.text
}

function buildSystemPrompt() {
  return composeAssistantSystemPrompt(effectiveKnowledgeOverride())
}


function loadLocalEnv(fileName) {
  const filePath = resolve(process.cwd(), fileName)

  if (!existsSync(filePath)) {
    return
  }

  for (const rawLine of readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim()

    if (!line || line.startsWith('#')) {
      continue
    }

    const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/)

    if (!match) {
      continue
    }

    const [, key, rawValue] = match

    if (process.env[key] !== undefined) {
      continue
    }

    let value = rawValue.trim()

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }

    process.env[key] = value
  }
}

